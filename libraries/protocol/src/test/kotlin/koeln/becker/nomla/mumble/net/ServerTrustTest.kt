package koeln.becker.nomla.mumble.net

import com.google.common.truth.Truth.assertThat
import org.junit.Assert.assertThrows
import org.junit.Test
import java.security.cert.CertificateException

class ServerTrustTest {
    private val system = TestCertificates.systemTrust()
    private val authType = "RSA"

    private fun manager(host: String, vararg pinned: TestCertificates.Issued) =
        ServerTrustManager(system, host, pinned.map { CertificatePins.fingerprint(it.certificate) }.toSet())

    /** Whether [presented] is trusted for [host] with [pins] pinned for it. */
    private fun check(
        host: String,
        presented: TestCertificates.Issued,
        vararg pins: TestCertificates.Issued,
    ): TrustFailure {
        val tm = manager(host, *pins)
        val thrown = runCatching { tm.checkServerTrusted(presented.chain, authType) }.exceptionOrNull()
        assertThat(thrown == null).isEqualTo(tm.failure == TrustFailure.NONE)
        if (tm.failure == TrustFailure.UNTRUSTED) {
            assertThat(thrown).isInstanceOf(CertificateException::class.java)
            assertThat(thrown).isNotInstanceOf(CertificateChangedException::class.java)
            assertThat(tm.serverChain).isEqualTo(presented.chain)
        }
        return tm.failure
    }

    @Test
    fun `a chain is trusted if the system trusts it for the host or it is pinned`() {
        val host = "mumble.example.org"
        val named = TestCertificates.leaf(dnsNames = listOf(host))
        val selfSigned = TestCertificates.leaf(dnsNames = listOf(host), selfSigned = true)
        val murmur = TestCertificates.leaf(selfSigned = true, cn = "Murmur Autogenerated Certificate v2")

        assertThat(check(host, named)).isEqualTo(TrustFailure.NONE)
        assertThat(check(host, TestCertificates.leaf(dnsNames = listOf("other.example.org"))))
            .isEqualTo(TrustFailure.UNTRUSTED)
        assertThat(check(host, selfSigned)).isEqualTo(TrustFailure.UNTRUSTED)
        // A pin needs no host name check.
        assertThat(check("10.0.0.5", murmur, murmur)).isEqualTo(TrustFailure.NONE)
        // A pinned host may move to a certificate the system trusts for it.
        assertThat(check(host, named, murmur)).isEqualTo(TrustFailure.NONE)
    }

    @Test
    fun `a certificate pinned for one host is not trusted for another`() {
        val leaf = TestCertificates.leaf(selfSigned = true)
        val store = TestCertificates.pinStore("a.example.org" to leaf.certificate)
        val tm = ServerTrustManager(system, "b.example.org", CertificatePins.forHost(store, "b.example.org"))

        assertThrows(CertificateException::class.java) { tm.checkServerTrusted(leaf.chain, authType) }
        assertThat(tm.failure).isEqualTo(TrustFailure.UNTRUSTED)
    }

    @Test
    fun `a pinned host presenting a different certificate reports a change`() {
        val pinned = TestCertificates.leaf(selfSigned = true)
        val presented = TestCertificates.leaf(selfSigned = true)
        val tm = manager("mumble.example.org", pinned)

        val e = assertThrows(CertificateChangedException::class.java) {
            tm.checkServerTrusted(presented.chain, authType)
        }

        assertThat(e.host).isEqualTo("mumble.example.org")
        assertThat(tm.failure).isEqualTo(TrustFailure.CHANGED)
    }

    @Test
    fun `a pinned certificate is trusted whatever names it carries`() {
        val forOtherHost = TestCertificates.leaf(dnsNames = listOf("other.example.org"))
        val noNames = TestCertificates.leaf(selfSigned = true, cn = "Murmur Autogenerated Certificate v2")

        assertThat(check("mumble.example.org", forOtherHost, forOtherHost)).isEqualTo(TrustFailure.NONE)
        assertThat(check("mumble.example.org", noNames, noNames)).isEqualTo(TrustFailure.NONE)
        assertThat(check("[2001:db8::1]", noNames, noNames)).isEqualTo(TrustFailure.NONE)
    }

    @Test
    fun `a system-trusted certificate for another host on a pinned host reports a change`() {
        val pinned = TestCertificates.leaf(selfSigned = true)
        val forOtherHost = TestCertificates.leaf(dnsNames = listOf("other.example.org"))

        assertThat(check("mumble.example.org", forOtherHost, pinned)).isEqualTo(TrustFailure.CHANGED)
    }

    @Test
    fun `a failure is cleared by the next successful check`() {
        val good = TestCertificates.leaf(dnsNames = listOf("mumble.example.org"))
        val bad = TestCertificates.leaf(selfSigned = true)
        val tm = manager("mumble.example.org")
        runCatching { tm.checkServerTrusted(bad.chain, authType) }

        tm.checkServerTrusted(good.chain, authType)

        assertThat(tm.failure).isEqualTo(TrustFailure.NONE)
    }

    @Test
    fun `pins are looked up by host case insensitively`() {
        val leaf = TestCertificates.leaf(selfSigned = true)
        val store = TestCertificates.pinStore("Mumble.Example.org" to leaf.certificate)

        assertThat(CertificatePins.forHost(store, "mumble.example.org."))
            .containsExactly(CertificatePins.fingerprint(leaf.certificate))
        assertThat(CertificatePins.forHost(store, "example.org")).isEmpty()
        assertThat(CertificatePins.forHost(null, "example.org")).isEmpty()
    }

    @Test
    fun `host names match subjectAltNames per RFC 6125`() {
        val leaf = TestCertificates.leaf(
            dnsNames = listOf("Mumble.Example.de", "*.example.org", "a*.example.net"),
            ipAddresses = listOf("192.0.2.7", "2001:db8::1"),
            cn = "cn-only.example.de",
        )
        fun m(host: String) = check(host, leaf) == TrustFailure.NONE

        assertThat(m("mumble.example.de")).isTrue()
        assertThat(m("MUMBLE.EXAMPLE.DE.")).isTrue()
        assertThat(m("other.example.de")).isFalse()
        assertThat(m("a.example.org")).isTrue()
        assertThat(m("example.org")).isFalse()
        assertThat(m("a.b.example.org")).isFalse()
        assertThat(m("ab.example.net")).isFalse()
        // The subject CN is not consulted when the certificate has subjectAltNames.
        assertThat(m("cn-only.example.de")).isFalse()
        assertThat(m("192.0.2.7")).isTrue()
        assertThat(m("192.0.2.8")).isFalse()
        assertThat(m("2001:db8:0:0:0:0:0:1")).isTrue()
        assertThat(m("[2001:db8::1]")).isTrue()
        assertThat(m("2001:db8::2")).isFalse()
        assertThat(m("")).isFalse()
    }

    @Test
    fun `a certificate without subjectAltNames matches nothing`() {
        val leaf = TestCertificates.leaf(cn = "mumble.example.org")
        assertThat(check("mumble.example.org", leaf)).isEqualTo(TrustFailure.UNTRUSTED)
    }

    /**
     * An IP literal is matched against IP SANs only, never against a DNS SAN that spells it, and a
     * literal that is not an exact address names no certificate.
     */
    @Test
    fun `an ip literal matches only an ip san with the same address`() {
        val leaf = TestCertificates.leaf(
            dnsNames = listOf("192.0.2.9", "127.1", "999.0.2.7"),
            ipAddresses = listOf("127.0.0.1"),
        )
        assertThat(check("192.0.2.9", leaf)).isEqualTo(TrustFailure.UNTRUSTED)
        assertThat(check("127.1", leaf)).isEqualTo(TrustFailure.UNTRUSTED)
        assertThat(check("999.0.2.7", leaf)).isEqualTo(TrustFailure.UNTRUSTED)
        assertThat(check("127.0.0.1", leaf)).isEqualTo(TrustFailure.NONE)
    }
}
